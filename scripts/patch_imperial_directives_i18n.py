LOCALE_OVERRIDES = {
    "de": KEYS_DE,
    "en": KEYS_EN,
}


def main() -> None:
    for path in sorted(LOCALES.glob("*.json")):
        lang = path.stem
        data = json.loads(path.read_text(encoding="utf-8"))
        patch = LOCALE_OVERRIDES.get(lang, KEYS_EN)
        data.update(patch)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        print(f"patched {path.name} (+{len(patch)} keys)")


if __name__ == "__main__":
    main()
